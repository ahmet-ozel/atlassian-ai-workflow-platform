# ---------------------------------------------------------------------------
# Web-shared TS twin: build / skip plumbing
# ---------------------------------------------------------------------------


_WEB_SHARED_DIR: Path = _WORKSPACE_ROOT / "libs" / "web-shared"
_DIST_SENSITIVE: Path = _WEB_SHARED_DIR / "dist" / "sensitive.js"
_PACKAGE_JSON: Path = _WEB_SHARED_DIR / "package.json"


def _resolve_node() -> str:
    """Return absolute path to ``node`` or ``pytest.skip``.

    The test skips cleanly when the Node binary is not on ``PATH``
    rather than failing; the parity guarantee is structural and a
    missing toolchain is a CI gap, not a regression.
    """

    node = shutil.which("node")
    if node is None:
        pytest.skip("node not available")
    return node


def _resolve_npm() -> str | None:
    """Return absolute path to ``npm``, or ``None`` if missing.

    ``None`` is a soft-fail: the build step will then ``pytest.skip``
    with a precise reason rather than crashing on ``FileNotFoundError``.
    """

    return shutil.which("npm")


def _run(argv: list[str], *, cwd: Path) -> subprocess.CompletedProcess[str]:
    """Run ``argv`` with text-mode stdout/stderr capture and a 5-min cap.

    The 5-minute cap exists so a hung ``npm install`` cannot stall the
    full property suite; in practice the install completes in seconds
    when the lockfile is present.
    """

    return subprocess.run(  # noqa: S603 - argv is fully constructed in-process.
        argv,
        cwd=str(cwd),
        capture_output=True,
        text=True,
        timeout=300,
    )


def _ensure_dist_sensitive_built() -> Path:
    """Return the path to ``dist/sensitive.js``, building it if needed.

    Skip semantics
    --------------
    * If ``package.json`` is missing the ``build`` script entry → skip
      with a precise message.
    * If ``node_modules`` is missing and ``npm`` is not on ``PATH`` →
      skip (no way to install ``typescript`` to drive ``tsc``).
    * If ``npm install`` or ``npm run build`` fails → skip with the
      command's stderr so a developer can reproduce the failure
      locally.

    The function is idempotent: once ``dist/sensitive.js`` exists it
    short-circuits, so the per-example cost during the property loop
    is zero.
    """

    if _DIST_SENSITIVE.is_file():
        return _DIST_SENSITIVE

    # Validate the build script up front so the skip message is
    # precise.
    try:
        package_meta = json.loads(_PACKAGE_JSON.read_text(encoding="utf-8"))
    except FileNotFoundError:
        pytest.skip(f"libs/web-shared/package.json missing: {_PACKAGE_JSON}")
    except json.JSONDecodeError as exc:  # pragma: no cover - defensive
        pytest.skip(f"libs/web-shared/package.json is not valid JSON: {exc}")
    scripts = package_meta.get("scripts") or {}
    if "build" not in scripts:
        pytest.skip(
            "libs/web-shared/package.json has no 'build' script"
        )

    npm = _resolve_npm()
    if npm is None:
        pytest.skip("npm not available; cannot build libs/web-shared/dist/sensitive.js")

    # Run ``npm install`` only when ``node_modules`` is absent - a
    # populated tree means the lockfile-driven install already
    # happened (developer machine or CI cache).
    if not (_WEB_SHARED_DIR / "node_modules").is_dir():
        install = _run(
            [npm, "install", "--no-audit", "--no-fund", "--silent"],
            cwd=_WEB_SHARED_DIR,
        )
        if install.returncode != 0:
            pytest.skip(
                "npm install failed for libs/web-shared "
                f"(exit={install.returncode}): {install.stderr.strip() or install.stdout.strip()}"
            )

    build = _run([npm, "run", "build", "--silent"], cwd=_WEB_SHARED_DIR)
    if build.returncode != 0:
        pytest.skip(
            "npm run build failed for libs/web-shared "
            f"(exit={build.returncode}): {build.stderr.strip() or build.stdout.strip()}"
        )

    if not _DIST_SENSITIVE.is_file():
        pytest.skip(
            f"npm run build succeeded but {_DIST_SENSITIVE} is still missing; "
            "check tsconfig output paths."
        )
    return _DIST_SENSITIVE


# Inline Node script that imports the compiled ESM module via a
# ``file://`` URL passed as ``argv[1]`` and reads a JSON list of keys
# from stdin. Stdout is a JSON list of booleans, parallel to the input
# list. Routing keys through stdin avoids Windows ``cmd.exe`` quoting
# pitfalls when the alphabet contains ``"`` or ``\\`` (``st.from_regex``
# does not generate these characters with the current strategy, but
# stdin is the more robust contract).
_NODE_PARITY_SCRIPT: str = (
    "(async () => {"
    "  const mod = await import(process.argv[1]);"
    "  let buf = '';"
    "  for await (const chunk of process.stdin) buf += chunk;"
    "  const keys = JSON.parse(buf);"
    "  process.stdout.write("
    "    JSON.stringify(keys.map((k) => mod.isSensitiveEnvKey(k)))"
    "  );"
    "})().catch((err) => { console.error(err && err.stack || String(err)); process.exit(1); });"
)


def _node_evaluate_keys(node: str, dist_path: Path, keys: list[str]) -> list[bool]:
    """Run the inline Node script once and return parity booleans.

    Single-process batching is critical: spawning Node per key would
    dominate the test runtime by an order of magnitude.
    """

    # ``Path.as_uri()`` produces a ``file:///`` URL on every platform
    # (including Windows drive letters), which is exactly what the
    # ESM loader expects.
    file_url = dist_path.resolve().as_uri()
    payload = json.dumps(keys, ensure_ascii=True)

    proc = subprocess.run(  # noqa: S603 - argv is fully constructed in-process.
        [node, "-e", _NODE_PARITY_SCRIPT, file_url],
        input=payload,
        capture_output=True,
        text=True,
        timeout=60,
    )
    if proc.returncode != 0:
        raise RuntimeError(
            "node parity helper failed "
            f"(exit={proc.returncode}): {proc.stderr.strip() or proc.stdout.strip()}"
        )

    try:
        result = json.loads(proc.stdout)
    except json.JSONDecodeError as exc:
        raise RuntimeError(
            f"node parity helper produced non-JSON stdout: {proc.stdout!r}"
        ) from exc

    if not isinstance(result, list) or len(result) != len(keys):
        raise RuntimeError(
            "node parity helper returned a list of unexpected shape: "
            f"len={len(result) if isinstance(result, list) else 'N/A'}, "
            f"expected={len(keys)}, payload={result!r}"
        )
    if not all(isinstance(b, bool) for b in result):
        raise RuntimeError(
            f"node parity helper returned non-bool entries: {result!r}"
        )
    return result


