"""Behavioral tests for Sensitive_Env_Key matcher TS ↔ Python parity.

For any uppercase environment-variable-style key drawn from
``[A-Z][A-Z0-9_]{3,40}``, the **Python** matcher
:func:`src.lifecycle.sensitive.is_sensitive_env_key` and the
**TypeScript** matcher :func:`isSensitiveEnvKey` (compiled from
``libs/web-shared/src/sensitive.ts`` to ``libs/web-shared/dist/sensitive.js``)
SHALL agree **bit-for-bit** on whether the key is a Sensitive_Env_Key.

This structural parity guarantee covers the form ``is_sensitive`` flag,
log redaction, and audit ``details_json`` redaction: both halves of the
control plane must converge on the *same* answer for every input or one
side could under-redact.

Strategy
--------
* Keys are generated by ``st.from_regex(r"[A-Z][A-Z0-9_]{3,40}",
  fullmatch=True)``. The fullmatch flag pins the regex
  to ``^…$`` so generated strings never contain newlines or
  characters outside the env-var alphabet - exactly the universe both
  matchers were designed for.

* Each Hypothesis example produces a **batch** of keys. A *single*
  Node invocation evaluates all of them in one shot and returns a
  JSON list of booleans. This keeps the test budget bounded:
  spawning ``node`` per key would multiply 30 examples × ~10 keys ×
  ~50 ms = ≥15 s; one process per example keeps the run well under a
  second on top of Hypothesis's own overhead.

* The Node side imports the compiled ESM module via a ``file://``
  URL and reads the JSON key list from stdin to side-step Windows
  command-line quoting issues.

Skip semantics
--------------
* ``shutil.which("node")`` returns ``None`` → ``pytest.skip("node
  not available")``.

* ``libs/web-shared/dist/sensitive.js`` does not exist → the fixture
  attempts ``npm run build`` (after a one-shot ``npm install`` if
  ``node_modules`` is missing). If either step fails, the test
  ``pytest.skip``s with the failing command and stderr captured for
  debugging.

* Concrete regression anchors run **after** the fixture has
  succeeded, so they share the same skip semantics as the property.

Concrete regression anchors
---------------------------
``test_concrete_regression_anchors`` exercises one example per
documented suffix (``_TOKEN``, ``_KEY``, ``_SECRET``, ``_PASSWORD``,
``_DSN``, ``_CREDENTIAL``) plus the ``_PRIVATE_`` infix and a few
known-negative names. These pin the property surface so a regression
in either matcher fails this file deterministically - independent of
the Hypothesis search order.
"""

from __future__ import annotations

import json
import shutil
import subprocess
import sys
from pathlib import Path
from typing import Iterable

import pytest
from hypothesis import HealthCheck, given, settings
from hypothesis import strategies as st

