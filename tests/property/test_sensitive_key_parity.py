# ---------------------------------------------------------------------------
# TS ↔ Python parity over a random key universe
# ---------------------------------------------------------------------------


# ``[A-Z][A-Z0-9_]{3,40}`` - uppercase env-var alphabet, length 4..41.
# ``fullmatch=True`` pins the regex to ``^…$`` so the generator cannot
# emit characters outside the documented universe (no newlines, no
# lowercase, no quotes); both matchers were specified against this
# alphabet.
_KEY_STRATEGY: st.SearchStrategy[str] = st.from_regex(
    r"[A-Z][A-Z0-9_]{3,40}", fullmatch=True
)


@given(
    keys=st.lists(_KEY_STRATEGY, min_size=1, max_size=12),
)
@settings(
    deadline=None,
    max_examples=30,
    suppress_health_check=[HealthCheck.function_scoped_fixture],
)
def test_python_and_typescript_matchers_agree(
    keys: list[str],
    node_binary: str,
    dist_sensitive_path: Path,
) -> None:
    """Python and TypeScript matchers agree on every key.

    The two halves are evaluated against the **same** input batch,
    then compared element-wise. Any divergence - in either direction
    (Python true / TS false, or vice versa) - fails the property and
    surfaces the offending key in Hypothesis's counterexample output.
    """

    py_results: list[bool] = [is_sensitive_env_key(k) for k in keys]
    ts_results: list[bool] = _node_evaluate_keys(
        node_binary, dist_sensitive_path, keys
    )

    assert ts_results == py_results, (
        "TS↔Python Sensitive_Env_Key parity broken. "
        f"keys={keys!r}, python={py_results!r}, typescript={ts_results!r}, "
        f"divergences={[ (k, py, ts) for k, py, ts in zip(keys, py_results, ts_results) if py != ts ]!r}"
    )


# ---------------------------------------------------------------------------
# Concrete regression anchors (one per documented suffix + infix +
# negatives). These pin the property surface so a regression in either
# matcher fails this file deterministically.
# ---------------------------------------------------------------------------


# ``(key, expected_sensitive)`` - covers each documented suffix at least
# once plus the ``_PRIVATE_`` infix and three known-negatives
# that exercise the "no leading underscore" boundary (``TOKEN`` etc.)
# referenced in the docstrings of both matcher modules.
_REGRESSION_CASES: tuple[tuple[str, bool], ...] = (
    # Suffix anchors
    ("VAULT_TOKEN", True),
    ("API_KEY", True),
    ("JWT_SECRET", True),
    ("DB_PASSWORD", True),
    ("POSTGRES_DSN", True),
    ("OAUTH_CREDENTIAL", True),
    # Infix anchor
    ("DB_PRIVATE_HOST", True),
    ("APP_PRIVATE_KEY_PATH", True),  # infix wins even when no suffix matches
    # Negatives - bare names that match the glob ``KEY`` etc. without
    # the leading underscore are NOT sensitive (mirrors the docstrings
    # in both matcher modules).
    ("TOKEN", False),
    ("KEY", False),
    ("SECRET", False),
    ("LOG_LEVEL", False),
    ("PORT", False),
    ("WORKER_NAME", False),
)


def _format_anchor(case: tuple[str, bool]) -> str:
    """Compact pytest-id renderer for the regression matrix."""

    key, expected = case
    return f"{key}->{ 'T' if expected else 'F' }"


@pytest.mark.parametrize(
    "case",
    _REGRESSION_CASES,
    ids=[_format_anchor(c) for c in _REGRESSION_CASES],
)
def test_concrete_regression_anchors(
    case: tuple[str, bool],
    node_binary: str,
    dist_sensitive_path: Path,
) -> None:
    """Concrete anchors covering every Sensitive_Env_Key pattern shape.

    Each case asserts three things at once:

    1. The Python matcher returns ``expected``.
    2. The TS matcher returns ``expected``.
    3. The two matchers agree (redundant given 1 + 2 but kept as an
       explicit assertion so the failure message names the parity
       contract directly).
    """

    key, expected = case

    py_result = is_sensitive_env_key(key)
    ts_result = _node_evaluate_keys(node_binary, dist_sensitive_path, [key])[0]

    assert py_result is expected, (
        f"Python matcher disagrees with anchor for {key!r}: "
        f"python={py_result!r}, expected={expected!r}"
    )
    assert ts_result is expected, (
        f"TypeScript matcher disagrees with anchor for {key!r}: "
        f"typescript={ts_result!r}, expected={expected!r}"
    )
    assert py_result == ts_result, (
        f"TS↔Python Sensitive_Env_Key parity broken on anchor {key!r}: "
        f"python={py_result!r}, typescript={ts_result!r}"
    )


def test_keys_strategy_alphabet_is_what_we_documented() -> None:
    """Sanity guard: the regex strategy never emits forbidden chars.

    Both matcher modules document an uppercase, no-newline universe;
    if a future edit relaxes ``_KEY_STRATEGY`` (e.g. allowing
    lowercase) without updating the matchers we want a fast,
    deterministic failure here rather than an obscure counterexample
    from the property test.
    """

    sample_keys: Iterable[str] = (
        # Hand-built representatives that hit each character class
        # the strategy is allowed to emit. If the strategy is ever
        # widened, pick samples that prove the new alphabet
        # explicitly rather than relying on this guard.
        "ABCD",  # 4 chars (lower bound)
        "Z9_3",  # mixes uppercase, digit, underscore
        "ABCDEFGHIJKLMNOPQRSTUVWXYZ_0123456789ABCD",  # 41 chars (upper bound)
    )
    for k in sample_keys:
        assert k.isascii(), f"alphabet guard: {k!r} is not ASCII"
        assert k[0].isupper(), f"alphabet guard: {k!r} does not start uppercase"
        for ch in k:
            assert ch.isupper() or ch.isdigit() or ch == "_", (
                f"alphabet guard: {k!r} contains forbidden char {ch!r}"
            )
        assert 4 <= len(k) <= 41, (
            f"alphabet guard: {k!r} length {len(k)} outside [4, 41]"
        )
