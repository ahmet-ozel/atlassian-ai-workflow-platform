_WORKSPACE_ROOT = Path(__file__).resolve().parents[2]
_SERVICE_ROOT = _WORKSPACE_ROOT / "services" / "admin-dashboard-api"
if str(_SERVICE_ROOT) not in sys.path:
    sys.path.insert(0, str(_SERVICE_ROOT))

